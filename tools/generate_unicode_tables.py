"""Generate src/model/unicode_tables.cpp from Python's Unicode database.

The tokenizer needs three pieces of Unicode data:
  * general categories: which code points are letters (L*) and numbers (N*)
  * the White_Space property
  * NFC normalization data: canonical decompositions, combining classes and
    the primary composites

Python's own `unicodedata.normalize("NFC", ...)` is the oracle for which
pairs may be recomposed, so composition exclusions come out right without a
separate data file.

Usage (from the repo root):
  python tools/generate_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "model" / "unicode_tables.cpp"
MAX_CODEPOINT = 0x10FFFF

# Hangul syllables are decomposed and composed algorithmically, not by table.
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3

# The White_Space property (PropList.txt). It is not exposed by unicodedata and
# has been stable since Unicode 6.3.
WHITE_SPACE = [
    0x0009, 0x000A, 0x000B, 0x000C, 0x000D, 0x0020, 0x0085, 0x00A0, 0x1680,
    *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F, 0x3000,
]

# Code points below this are never changed by NFC and never take part in a
# composition, which gives the normalizer a fast path for ASCII and Latin-1.
NFC_FAST_PATH_LIMIT = 0x300


def ranges(predicate) -> list[tuple[int, int]]:
    """Collapse all code points matching `predicate` into inclusive ranges."""
    result = []
    for cp in range(MAX_CODEPOINT + 1):
        if not predicate(cp):
            continue
        if result and result[-1][1] == cp - 1:
            result[-1] = (result[-1][0], cp)
        else:
            result.append((cp, cp))
    return result


def category_ranges(prefix: str) -> list[tuple[int, int]]:
    return ranges(lambda cp: unicodedata.category(chr(cp)).startswith(prefix))


def canonical_decomposition(cp: int) -> list[int] | None:
    """The one-level canonical decomposition of `cp`, or None."""
    fields = unicodedata.decomposition(chr(cp)).split()
    if not fields or fields[0].startswith("<"):   # none, or a compatibility mapping
        return None
    return [int(field, 16) for field in fields]


def combining_class_ranges() -> list[tuple[int, int, int]]:
    result = []
    for cp in range(MAX_CODEPOINT + 1):
        ccc = unicodedata.combining(chr(cp))
        if ccc == 0:
            continue
        if result and result[-1][1] == cp - 1 and result[-1][2] == ccc:
            result[-1] = (result[-1][0], cp, ccc)
        else:
            result.append((cp, cp, ccc))
    return result


def decompositions() -> list[tuple[int, list[int]]]:
    result = []
    for cp in range(MAX_CODEPOINT + 1):
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        mapping = canonical_decomposition(cp)
        if mapping:
            result.append((cp, mapping))
    return result


def compositions() -> list[tuple[int, int, int]]:
    """(first, second, composite) for every pair that NFC recomposes."""
    result = []
    for cp, mapping in decompositions():
        if len(mapping) == 2 and unicodedata.normalize("NFC", chr(mapping[0]) + chr(mapping[1])) == chr(cp):
            result.append((mapping[0], mapping[1], cp))
    return sorted(result)


def check_fast_path(composition_pairs) -> None:
    for cp in range(NFC_FAST_PATH_LIMIT):
        assert unicodedata.normalize("NFC", chr(cp)) == chr(cp), hex(cp)
        assert unicodedata.combining(chr(cp)) == 0, hex(cp)
    for first, second, _ in composition_pairs:
        assert not (first < NFC_FAST_PATH_LIMIT and second < NFC_FAST_PATH_LIMIT), (hex(first), hex(second))


def format_rows(rows: list[str], per_line: int) -> str:
    lines = []
    for i in range(0, len(rows), per_line):
        lines.append("    " + " ".join(rows[i:i + per_line]))
    return "\n".join(lines)


def main() -> None:
    letters = category_ranges("L")
    numbers = category_ranges("N")
    white_space = ranges(lambda cp: cp in WHITE_SPACE)
    ccc = combining_class_ranges()
    decomps = decompositions()
    comps = compositions()
    check_fast_path(comps)

    flat: list[int] = []
    decomp_rows = []
    for cp, mapping in decomps:
        decomp_rows.append(f"{{0x{cp:X}, {len(flat)}, {len(mapping)}}},")
        flat.extend(mapping)
    assert len(flat) < 2**16, "Decomposition offsets must fit in 16 bits"

    def range_rows(rs):
        return [f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs]

    out = f"""// Generated by tools/generate_unicode_tables.py from Unicode {unicodedata.unidata_version}
// (Python {sys.version_info.major}.{sys.version_info.minor} unicodedata). Do not edit by hand.

#include "model/unicode_tables.hpp"

namespace murmur::unicode::tables {{

namespace {{

constexpr CodepointRange kLetterRanges[] = {{
{format_rows(range_rows(letters), 4)}
}};

constexpr CodepointRange kNumberRanges[] = {{
{format_rows(range_rows(numbers), 4)}
}};

constexpr CodepointRange kWhiteSpaceRanges[] = {{
{format_rows(range_rows(white_space), 4)}
}};

constexpr CombiningClassRange kCombiningClassRanges[] = {{
{format_rows([f"{{0x{a:X}, 0x{b:X}, {c}}}," for a, b, c in ccc], 3)}
}};

constexpr Decomposition kDecompositions[] = {{
{format_rows(decomp_rows, 4)}
}};

constexpr char32_t kDecompositionData[] = {{
{format_rows([f"0x{cp:X}," for cp in flat], 8)}
}};

constexpr Composition kCompositions[] = {{
{format_rows([f"{{0x{a:X}, 0x{b:X}, 0x{c:X}}}," for a, b, c in comps], 3)}
}};

}}  // namespace

std::span<const CodepointRange> LetterRanges() {{ return kLetterRanges; }}
std::span<const CodepointRange> NumberRanges() {{ return kNumberRanges; }}
std::span<const CodepointRange> WhiteSpaceRanges() {{ return kWhiteSpaceRanges; }}
std::span<const CombiningClassRange> CombiningClassRanges() {{ return kCombiningClassRanges; }}
std::span<const Decomposition> Decompositions() {{ return kDecompositions; }}
std::span<const char32_t> DecompositionData() {{ return kDecompositionData; }}
std::span<const Composition> Compositions() {{ return kCompositions; }}

}}  // namespace murmur::unicode::tables
"""
    OUTPUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.name}: {len(letters)} letter ranges, {len(numbers)} number ranges, "
          f"{len(ccc)} combining-class ranges, {len(decomps)} decompositions, {len(comps)} compositions")


if __name__ == "__main__":
    main()
